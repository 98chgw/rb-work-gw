def summary_from_html(body, name):
    """3-1·3-2 h4 제목과 첫 두 항목으로 요약 패널 생성"""
    def part(h3a, h3b):
        i = body.find(h3a); j = body.find(h3b, i + 1) if h3b else -1
        seg = body[i:j if j > 0 else None]
        its = []
        for m in re.finditer(r'<h4>(.*?)</h4>\s*<ul>(.*?)</ul>', seg, re.S):
            t = re.sub(r'\s+', ' ', m.group(1)).strip()
            tag = re.search(r'<span class="tag">\((.*?)\)</span>', t)
            title = re.sub(r'<span class="tag">.*?</span>', '', t).strip()
            lis = [re.sub(r'\s+', ' ', re.sub(r'<span class="src".*?</span>', '', x, flags=re.S)).strip() for x in re.findall(r'<li>(.*?)</li>', m.group(2), re.S)][:2]
            lis = [re.sub(r'<[^>]+>', '', x) for x in lis]
            lis = [x if len(x) < 90 else x[:88] + '…' for x in lis]
            its.append((title, tag.group(1) if tag else '', lis))
        return its
    prob = part('3-1.', '3-2.'); pot = part('3-2.', '<h2>4')
    h = [f'<section class="qs"><h2 class="qs-title">{name} 요약 (지역현안 · 발전방향)</h2>']
    for cls, tag, its in (('p-prob', '주요 문제점', prob), ('p-pot', '주요 잠재력', pot)):
        h.append(f'<div class="panel {cls}"><span class="ptag">{tag}</span>')
        for t, tg, lis in its:
            h.append(f'<div class="it"><h5>{t}<span class="lk">({tg})</span></h5><ul>' + ''.join(f'<li>{x}</li>' for x in lis) + '</ul></div>')
        h.append('</div>')
    h.append('</section>')
    return '\n'.join(h)


def augment(D):
    s = open(D['file'], encoding='utf-8').read()
    body = s[s.find('<body'):]
    body = body[body.find('>') + 1:body.rfind('</body>')]
    body = re.sub(r'<div class="refs">.*?</div>', '', body, flags=re.S)
    # 한눈에 보기에 한 줄 추가
    body = body.replace('<span class="src"', f'<br />· {D["fact_add"]}<span class="src"', 1)
    # 4-2 바로 뒤 변경 박스
    body = re.sub(r'(<h3>4-2\.[^<]*</h3>)', r'\1\n<div class="check">' + D['change'].replace('\\', '\\\\') + '</div>', body, count=1)
    # FGI 미제시 후보 표시
    for k in D['non_fgi']:
        body = re.sub(r'(<span class="k">)' + re.escape(k) + r'([^<]*)(</span>)', r'\1' + k + r'\2 <span class="tag t-r">FGI 미제시 · 추가 검토</span>\3', body, count=1)
    # 확인 필요 사항 추가
    extra = ''.join(f'<br />· {x}' for x in D['checks'])
    body = re.sub(r'(<strong>확인 필요 사항</strong>.*?)(\s*</div>)', lambda m: m.group(1) + extra + m.group(2), body, count=1, flags=re.S)
    # FGI·지도 섹션 삽입 (종합 발전방향 앞)
    T = dict(name=D['name'], fgi=D['fgi'], gis=D['gis'])
    ins = G.fgi(T) + '\n' + G.gis(T)
    body = body.replace('<h2>종합 발전방향</h2>', ins + '\n<h2>종합 발전방향</h2>', 1)
    if D['add_summary']:
        body = body.rstrip() + '\n' + summary_from_html(body, D['name']) + '\n' + G.glossary()
    open(f'/tmp/claude-0/iss/out/{D["id"]}.body.html', 'w', encoding='utf-8').write(body)
    print(D['id'], len(body))


for D in (JS, GH):
    augment(D)
