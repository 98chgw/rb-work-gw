def zstr(z):
    return ', '.join(f'{k.replace("지역", "")} {v:g}%' for k, v in list(z.items())[:3])


def tbl_rows(t, lst):
    r = []
    for x in lst:
        ri = '·'.join(x['ri']) if isinstance(x.get('ri'), list) else ''
        if t == 'village':
            j = OK if x['ok'] else (CO + '<br><small>25m 경계 시</small>' if x['ok25'] else NO)
            r.append(f"<tr><td>{x['id']}</td><td>{ri}</td><td>{x['rep']} 일원</td><td>{x['n_res']}</td><td>{x['area']/1e4:.1f}ha</td><td>{x['ratio']:g}% · {x['dens']:g}</td><td>{x['ratio25']:g}% · {x['dens25']:g}</td><td>{zstr(x['zdet'])}</td><td>{j}</td></tr>")
        elif t == 'industry':
            r.append(f"<tr><td>{x['id']}</td><td>{ri}</td><td>{x['rep']} 일원</td><td>{x['n']}</td><td>{x['area']/1e4:.1f}ha</td><td>{zstr(x['zdet'])}</td><td>{OK if x['ok'] else NO}</td></tr>")
        elif t == 'livestock':
            r.append(f"<tr><td>{x['id']}</td><td>{ri}</td><td>{x['rep']} 일원</td><td>{x['n']}</td><td>{x['liv_area']/1e4:.1f}ha</td><td>{zstr(x['zdet'])}</td><td>{CO}<br><small>축사 면적비는 건축물 확인</small></td></tr>")
        elif t == 'energy':
            r.append(f"<tr><td>{x['id']}</td><td>{ri}</td><td>{x['rep']} 일원</td><td>{x['n']}</td><td>{x['area']/1e4:.1f}ha</td><td>{zstr(x['zdet'])}</td><td>{x['scale']}</td></tr>")
        elif t == 'farm':
            tags = [k for k, f in [('과수·전략작물 10ha', x['t10']), ('친환경 20ha', x['t20']), ('친환경 쌀(논 50ha)', x['t50rice']), ('고품질쌀(논 100ha)', x['t100rice'])] if f]
            r.append(f"<tr><td>{x['id']}</td><td>{ri}</td><td>{x['rep']} 일원</td><td>{x['area']/1e4:.1f}ha</td><td>{x['dap']/1e4:.1f}ha</td><td>{zstr(x['zdet'])}</td><td>{' · '.join(tags)}</td></tr>")
        elif t == 'fusion':
            r.append(f"<tr><td>{x['id']}</td><td>{x['name']}</td><td>{x['addr']}</td><td>{x['zone_at']}</td><td>{x['ma_area']/1e4:.1f}ha</td><td>{OK if x['ok'] else NO}</td></tr>")
    return ''.join(r)


