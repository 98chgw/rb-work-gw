SECS = [('s1', r'^1\. .*사업 추진 현황'), ('s2', r'^2\. .*자원 현황'), ('s31', r'^3-1\.'), ('s32', r'^3-2\.'),
        ('s41', r'^4-1\.'), ('s42', r'^4-2\.'), ('s43', r'^4-3\.'), ('s5', r'주민 의견 \(FGI\)'),
        ('s61', r'^[56]-1\. 지역현안 지도'), ('s62', r'^[56]-2\. 발전방향 지도'), ('s7', r'지정 기준 검토'), ('sv', r'^종합 발전방향')]


def add_why(body, tid):
    if 'class="why"' in body: return body
    C = content(tid)
    if tid == 'hwaam':  # 화암 문서는 지도 절이 5장, SHP 절이 4-5
        for k in C:
            C[k] = C[k].replace('6-1', '5-1').replace('6-2', '5-2').replace('7장', '4-5')
    heads = [(m.start(), m.end(), re.sub(r'<[^>]+>', '', m.group(2)).strip()) for m in re.finditer(r'<(h2|h3)[^>]*>(.*?)</\1>', body, re.S)]
    ins = []
    for key, pat in SECS:
        for k, (s, e, t) in enumerate(heads):
            if re.search(pat, t):
                end = heads[k + 1][0] if k + 1 < len(heads) else len(body)
                ins.append((end, C[key]))
                break
    for pos, frag in sorted(ins, key=lambda x: -x[0]):
        body = body[:pos] + frag + '\n' + body[pos:]
    return body
